/** Иконки с собственной сеткой (двухцветные мастера). */
const VIEWBOX: Partial<Record<IconName, string>> = {
  hammer: '0 0 1052 985',
};

export function icon(name: IconName, size = 16): string {
  const vb = VIEWBOX[name] ?? '0 0 24 24';
  return `<svg class="icon" width="${size}" height="${size}" viewBox="${vb}" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
}

/** Заполняет все элементы с data-icon соответствующими SVG. */
export function applyIcons(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => {
    const name = el.dataset.icon as IconName;
    if (name in PATHS) el.innerHTML = icon(name, Number(el.dataset.iconSize ?? 16));
  });
}
